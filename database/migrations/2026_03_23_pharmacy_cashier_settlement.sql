BEGIN;

ALTER TABLE public.pharmacy_sale
  ADD COLUMN IF NOT EXISTS settlement_channel text,
  ADD COLUMN IF NOT EXISTS settlement_status text,
  ADD COLUMN IF NOT EXISTS settled_at timestamp without time zone,
  ADD COLUMN IF NOT EXISTS settled_by integer REFERENCES public.staff(staff_id);

UPDATE public.pharmacy_sale
SET
  settlement_channel = COALESCE(settlement_channel, CASE WHEN COALESCE(due_amount, 0) > 0 THEN 'cashier' ELSE 'pharmacy' END),
  settlement_status = COALESCE(settlement_status, CASE WHEN COALESCE(due_amount, 0) > 0 THEN 'pending' ELSE 'settled' END),
  settled_at = CASE
    WHEN settled_at IS NULL AND COALESCE(due_amount, 0) = 0 THEN sale_timestamp
    ELSE settled_at
  END
WHERE settlement_channel IS NULL
   OR settlement_status IS NULL
   OR (settled_at IS NULL AND COALESCE(due_amount, 0) = 0);

-- Reconcile legacy inconsistencies safely and idempotently.
UPDATE public.pharmacy_sale
SET
  settlement_status = CASE
    WHEN COALESCE(due_amount, 0) <= 0 THEN 'settled'
    ELSE 'pending'
  END,
  settlement_channel = COALESCE(
    settlement_channel,
    CASE
      WHEN COALESCE(due_amount, 0) <= 0 THEN 'pharmacy'
      ELSE 'cashier'
    END
  ),
  settled_at = CASE
    WHEN COALESCE(due_amount, 0) <= 0 THEN COALESCE(settled_at, sale_timestamp)
    ELSE NULL
  END,
  settled_by = CASE
    WHEN COALESCE(due_amount, 0) <= 0 THEN settled_by
    ELSE NULL
  END
WHERE
  (COALESCE(due_amount, 0) <= 0 AND settlement_status <> 'settled')
  OR (COALESCE(due_amount, 0) > 0 AND settlement_status <> 'pending')
  OR (COALESCE(due_amount, 0) <= 0 AND settled_at IS NULL)
  OR (COALESCE(due_amount, 0) > 0 AND (settled_at IS NOT NULL OR settled_by IS NOT NULL))
  OR settlement_channel IS NULL;

ALTER TABLE public.pharmacy_sale
  ALTER COLUMN settlement_channel SET DEFAULT 'pharmacy',
  ALTER COLUMN settlement_status SET DEFAULT 'settled';

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'pharmacy_sale_settlement_channel_check'
  ) THEN
    ALTER TABLE public.pharmacy_sale
      ADD CONSTRAINT pharmacy_sale_settlement_channel_check
      CHECK (settlement_channel IN ('pharmacy', 'cashier'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'pharmacy_sale_settlement_status_check'
  ) THEN
    ALTER TABLE public.pharmacy_sale
      ADD CONSTRAINT pharmacy_sale_settlement_status_check
      CHECK (settlement_status IN ('pending', 'settled'));
  END IF;
END$$;

