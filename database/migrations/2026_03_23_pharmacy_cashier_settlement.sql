  txn_type text NOT NULL DEFAULT 'payment',
  reversed_from_txn_id bigint REFERENCES public.cashier_payment_txn(cashier_payment_txn_id),
  reversal_reason_code text,
  reversal_reason_note text,
  payment_type character varying(50) NOT NULL,
  payment_reference character varying(150),
  receipt_no character varying(80),
  notes text,
  received_by integer REFERENCES public.staff(staff_id),
  created_at timestamp without time zone NOT NULL DEFAULT now(),
  CONSTRAINT cashier_payment_txn_amount_check CHECK (amount <> 0),
  CONSTRAINT cashier_payment_txn_type_check CHECK (txn_type IN ('payment', 'reversal'))
);

ALTER TABLE public.cashier_payment_txn
  ADD COLUMN IF NOT EXISTS txn_type text NOT NULL DEFAULT 'payment',
  ADD COLUMN IF NOT EXISTS reversed_from_txn_id bigint REFERENCES public.cashier_payment_txn(cashier_payment_txn_id),
  ADD COLUMN IF NOT EXISTS reversal_reason_code text,
  ADD COLUMN IF NOT EXISTS reversal_reason_note text,
  ADD COLUMN IF NOT EXISTS receipt_no character varying(80);

DO $$
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'cashier_payment_txn_amount_check'
      AND conrelid = 'public.cashier_payment_txn'::regclass
  ) THEN
    ALTER TABLE public.cashier_payment_txn
      DROP CONSTRAINT cashier_payment_txn_amount_check;
  END IF;
END$$;

ALTER TABLE public.cashier_payment_txn
  ADD CONSTRAINT cashier_payment_txn_amount_check CHECK (amount <> 0);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'cashier_payment_txn_type_check'
      AND conrelid = 'public.cashier_payment_txn'::regclass
  ) THEN
    ALTER TABLE public.cashier_payment_txn
      ADD CONSTRAINT cashier_payment_txn_type_check CHECK (txn_type IN ('payment', 'reversal'));
  END IF;
END$$;

