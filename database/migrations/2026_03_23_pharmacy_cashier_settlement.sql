  ON public.bill_pharmacy_sale (settlement_status);

CREATE TABLE IF NOT EXISTS public.cashier_payment_txn (
  cashier_payment_txn_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
