BEGIN;

-- Ensure settlement columns exist and have safe defaults.
ALTER TABLE public.pharmacy_sale
  ADD COLUMN IF NOT EXISTS settlement_channel text,
  ADD COLUMN IF NOT EXISTS settlement_status text,
  ADD COLUMN IF NOT EXISTS settled_at timestamp without time zone,
  ADD COLUMN IF NOT EXISTS settled_by integer REFERENCES public.staff(staff_id);

ALTER TABLE public.pharmacy_sale
  ALTER COLUMN settlement_channel SET DEFAULT 'pharmacy',
  ALTER COLUMN settlement_status SET DEFAULT 'settled';

-- Ensure expected settlement constraints exist.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'pharmacy_sale_settlement_channel_check'
      AND conrelid = 'public.pharmacy_sale'::regclass
  ) THEN
    ALTER TABLE public.pharmacy_sale
      ADD CONSTRAINT pharmacy_sale_settlement_channel_check
      CHECK (settlement_channel IN ('pharmacy', 'cashier'));
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'pharmacy_sale_settlement_status_check'
      AND conrelid = 'public.pharmacy_sale'::regclass
  ) THEN
    ALTER TABLE public.pharmacy_sale
      ADD CONSTRAINT pharmacy_sale_settlement_status_check
      CHECK (settlement_status IN ('pending', 'settled'));
  END IF;
END$$;

-- Reconcile settlement fields for legacy rows.
UPDATE public.pharmacy_sale
SET
  settlement_channel = COALESCE(
    settlement_channel,
    CASE WHEN COALESCE(due_amount, 0) > 0 THEN 'cashier' ELSE 'pharmacy' END
  ),
  settlement_status = CASE
    WHEN COALESCE(due_amount, 0) > 0 THEN 'pending'
    ELSE 'settled'
  END,
  settled_at = CASE
    WHEN COALESCE(due_amount, 0) > 0 THEN NULL
    ELSE COALESCE(settled_at, sale_timestamp)
  END,
  settled_by = CASE
    WHEN COALESCE(due_amount, 0) > 0 THEN NULL
    ELSE settled_by
  END
WHERE
  settlement_channel IS NULL
  OR settlement_status IS NULL
  OR (COALESCE(due_amount, 0) > 0 AND settlement_status <> 'pending')
  OR (COALESCE(due_amount, 0) <= 0 AND settlement_status <> 'settled')
  OR (COALESCE(due_amount, 0) <= 0 AND settled_at IS NULL)
  OR (COALESCE(due_amount, 0) > 0 AND (settled_at IS NOT NULL OR settled_by IS NOT NULL));

-- Patch drift: this table is expected by cashier draft routes.
CREATE TABLE IF NOT EXISTS public.cashier_settlement_draft (
  cashier_settlement_draft_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bill_id integer NOT NULL REFERENCES public.bill(bill_id) ON DELETE CASCADE,
  visit_id integer REFERENCES public.visit(visit_id) ON DELETE SET NULL,
  amount numeric(12,2) NOT NULL,
  payment_type character varying(50) NOT NULL,
  payment_reference character varying(150),
  notes text,
  draft_status text NOT NULL DEFAULT 'open',
  created_by integer REFERENCES public.staff(staff_id),
  applied_cashier_payment_txn_id bigint REFERENCES public.cashier_payment_txn(cashier_payment_txn_id),
  created_at timestamp without time zone NOT NULL DEFAULT now(),
  updated_at timestamp without time zone NOT NULL DEFAULT now(),
  CONSTRAINT cashier_settlement_draft_amount_check CHECK (amount > 0),
  CONSTRAINT cashier_settlement_draft_status_check CHECK (draft_status IN ('open', 'applied', 'cancelled'))
);

CREATE INDEX IF NOT EXISTS idx_cashier_settlement_draft_bill
  ON public.cashier_settlement_draft (bill_id, draft_status, created_at DESC);

